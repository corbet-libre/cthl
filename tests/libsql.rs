//! Real application-storage fixtures; throttle state always stays in memory.
//! Driver errors are replaced by static labels so remote credentials and URLs
//! cannot appear in test failure diagnostics.

use std::{num::NonZeroUsize, sync::Arc, time::Duration};

use cthl::{Decision, FakeRelativeClock, Limit, MemoryStore, Store, Throttle};
use libsql::{Builder, Connection, Database, params};

type TestResult<T = ()> = Result<T, &'static str>;

fn require(condition: bool, message: &'static str) -> TestResult {
    if condition { Ok(()) } else { Err(message) }
}

async fn create_table(connection: &Connection, table: &str) -> TestResult {
    // The table name is generated by this test, never from a caller or env var.
    connection
        .execute(
            &format!(
                "CREATE TABLE {table} (
                    community TEXT NOT NULL,
                    resource TEXT NOT NULL,
                    value INTEGER NOT NULL CHECK (value >= 0),
                    PRIMARY KEY (community, resource)
                ) WITHOUT ROWID"
            ),
            (),
        )
        .await
        .map_err(|_| "create fixture table failed")?;
    Ok(())
}

async fn read_value(connection: &Connection, table: &str, community: &str) -> TestResult<i64> {
    let mut rows = connection
        .query(
            &format!("SELECT value FROM {table} WHERE community = ?1 AND resource = ?2"),
            params![community, "example-setting"],
        )
        .await
        .map_err(|_| "indexed read failed")?;
    let row = rows
        .next()
        .await
        .map_err(|_| "read row failed")?
        .ok_or("expected fixture row missing")?;
    row.get(0).map_err(|_| "read value failed")
}

async fn guarded_write<S: Store>(
    throttle: &Throttle<S>,
    connection: &Connection,
    table: &str,
    community: &str,
) -> TestResult<Decision> {
    let decision = throttle
        .check(b"opaque-test-key", "update-setting")
        .await
        .map_err(|_| "throttle check failed")?;
    if decision == Decision::Allowed {
        connection
            .execute(
                &format!(
                    "INSERT INTO {table} (community, resource, value) VALUES (?1, ?2, 1)
                     ON CONFLICT (community, resource) DO UPDATE SET value = value + 1"
                ),
                params![community, "example-setting"],
            )
            .await
            .map_err(|_| "guarded write failed")?;
    }
    Ok(decision)
}

async fn exercise(connection: &Connection, table: &str) -> TestResult {
    let clock = FakeRelativeClock::default();
    let store = Arc::new(MemoryStore::with_clock(
        NonZeroUsize::new(8).unwrap(),
        clock.clone(),
    ));
    let policy = [(
        "update-setting",
        Limit::new(1, Duration::from_secs(1)).unwrap(),
    )];
    let a = Throttle::new("community-a", policy, store.clone()).unwrap();
    let b = Throttle::new("community-b", policy, store).unwrap();

    require(
        guarded_write(&a, connection, table, "community-a").await? == Decision::Allowed,
        "first write should pass",
    )?;
    require(
        guarded_write(&a, connection, table, "community-a").await?
            == Decision::Denied {
                retry_after: Duration::from_secs(1),
            },
        "repeated write should be denied",
    )?;
    require(
        guarded_write(&b, connection, table, "community-b").await? == Decision::Allowed,
        "second community should have separate quota",
    )?;
    require(
        read_value(connection, table, "community-a").await? == 1,
        "denied write changed data",
    )?;
    require(
        read_value(connection, table, "community-b").await? == 1,
        "community isolation failed",
    )?;

    clock.advance(Duration::from_secs(1));
    require(
        guarded_write(&a, connection, table, "community-a").await? == Decision::Allowed,
        "write should pass after replenishment",
    )?;
    require(
        read_value(connection, table, "community-a").await? == 2,
        "updated value missing",
    )?;
    require(
        read_value(connection, table, "community-b").await? == 1,
        "update leaked between communities",
    )?;

    let select = format!("SELECT value FROM {table} WHERE community = ?1 AND resource = ?2");
    let update =
        format!("UPDATE {table} SET value = value + 1 WHERE community = ?1 AND resource = ?2");
    let delete = format!("DELETE FROM {table} WHERE community = ?1 AND resource = ?2");
    for sql in [&select, &update, &delete] {
        let mut plan = connection
            .query(
                &format!("EXPLAIN QUERY PLAN {sql}"),
                params!["community-a", "example-setting"],
            )
            .await
            .map_err(|_| "query plan failed")?;
        let mut indexed = false;
        while let Some(row) = plan.next().await.map_err(|_| "query plan row failed")? {
            let detail: String = row.get(3).map_err(|_| "query plan detail failed")?;
            require(!detail.contains("SCAN"), "query uses a table scan")?;
            indexed |= detail.contains("SEARCH") && detail.contains("PRIMARY KEY");
        }
        require(indexed, "query did not use the composite primary key")?;
    }

    // A successful admission is not a promise that the application transaction
    // will commit. Real rollback must preserve data without refunding quota.
    clock.advance(Duration::from_secs(1));
    require(
        a.check(b"opaque-test-key", "update-setting")
            .await
            .map_err(|_| "check failed")?
            == Decision::Allowed,
        "transaction admission failed",
    )?;
    let transaction = connection
        .transaction()
        .await
        .map_err(|_| "begin transaction failed")?;
    transaction
        .execute(&update, params!["community-a", "example-setting"])
        .await
        .map_err(|_| "transaction update failed")?;
    transaction
        .rollback()
        .await
        .map_err(|_| "rollback failed")?;
    require(
        read_value(connection, table, "community-a").await? == 2,
        "rollback changed data",
    )?;
    require(
        matches!(
            a.check(b"opaque-test-key", "update-setting").await,
            Ok(Decision::Denied { .. })
        ),
        "rollback incorrectly refunded quota",
    )?;

    clock.advance(Duration::from_secs(1));
    require(
        a.check(b"opaque-test-key", "update-setting")
            .await
            .map_err(|_| "check failed")?
            == Decision::Allowed,
        "constraint test admission failed",
    )?;
    require(
        connection
            .execute(
                &format!("UPDATE {table} SET value = -1 WHERE community = ?1 AND resource = ?2"),
                params!["community-a", "example-setting"],
            )
            .await
            .is_err(),
        "database constraint failure was not surfaced",
    )?;
    require(
        read_value(connection, table, "community-a").await? == 2,
        "constraint failure changed data",
    )?;
    require(
        matches!(
            a.check(b"opaque-test-key", "update-setting").await,
            Ok(Decision::Denied { .. })
        ),
        "database failure incorrectly refunded quota",
    )?;
    Ok(())
}

async fn run_fixture(db: &Database, table: &str) -> TestResult {
    let connection = db.connect().map_err(|_| "connect failed")?;
    tokio::time::timeout(Duration::from_secs(15), create_table(&connection, table))
        .await
        .map_err(|_| "create fixture table timed out")??;
    let result = tokio::time::timeout(Duration::from_secs(45), exercise(&connection, table))
        .await
        .map_err(|_| "fixture timed out")
        .and_then(|result| result);
    // Try cleanup after both success and failure, including an exercise timeout.
    let cleanup = tokio::time::timeout(
        Duration::from_secs(10),
        connection.execute(&format!("DROP TABLE {table}"), ()),
    )
    .await
    .map_err(|_| "cleanup timed out")?
    .map_err(|_| "fixture cleanup failed");
    result?;
    cleanup?;
    Ok(())
}

#[tokio::test]
async fn in_memory_libsql_round_trip() -> TestResult {
    let db = Builder::new_local(":memory:")
        .build()
        .await
        .map_err(|_| "open local DB failed")?;
    run_fixture(&db, "cthl_fixture").await
}

#[tokio::test]
async fn file_database_retains_only_application_state_on_reopen() -> TestResult {
    let directory = tempfile::tempdir().map_err(|_| "create temp directory failed")?;
    let path = directory.path().join("application.db");
    {
        let db = Builder::new_local(&path)
            .build()
            .await
            .map_err(|_| "open file DB failed")?;
        let connection = db.connect().map_err(|_| "connect file DB failed")?;
        create_table(&connection, "cthl_fixture").await?;
        exercise(&connection, "cthl_fixture").await?;
    }
    let db = Builder::new_local(&path)
        .build()
        .await
        .map_err(|_| "reopen file DB failed")?;
    let connection = db.connect().map_err(|_| "reconnect file DB failed")?;
    require(
        read_value(&connection, "cthl_fixture", "community-a").await? == 2,
        "reopened data differs",
    )?;
    require(
        read_value(&connection, "cthl_fixture", "community-b").await? == 1,
        "reopened community isolation failed",
    )?;
    Ok(())
}

#[tokio::test]
async fn turso_round_trip_if_configured() -> TestResult {
    let (Some(url), Some(token)) = (
        std::env::var_os("TURSO_URL"),
        std::env::var_os("TURSO_TOKEN"),
    ) else {
        eprintln!("skipped Turso round trip: TURSO_URL and TURSO_TOKEN are both required");
        return Ok(());
    };
    let url = url
        .into_string()
        .map_err(|_| "invalid TURSO_URL encoding")?;
    let token = token
        .into_string()
        .map_err(|_| "invalid TURSO_TOKEN encoding")?;
    require(
        !url.is_empty() && !token.is_empty(),
        "empty Turso configuration",
    )?;
    let db = tokio::time::timeout(
        Duration::from_secs(15),
        Builder::new_remote(url, token).build(),
    )
    .await
    .map_err(|_| "Turso connection timed out")?
    .map_err(|_| "Turso connection failed")?;
    let nonce = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_err(|_| "fixture clock failed")?
        .as_nanos();
    let table = format!("cthl_fixture_{}_{nonce}", std::process::id());
    run_fixture(&db, &table).await
}
